-- =====================================================================
-- 社会保険の資格取得日・喪失日を持たせ、月ごとに自動判定する
-- =====================================================================
-- これまで加入の有無は profiles.shaho_enrolled の1つのフラグだけで、
-- 月の区別が無かった。そのため「10月から加入」を先にオンにすると
-- 8月・9月の給与からも社保が引かれてしまい、給与を締めるたびに
-- 手でオン・オフを切り替える運用になっていた（実際に7月の振込で
-- 誤って引かれたファイルを作りかけている）。
--
-- 資格取得日を入れておけば、その月より前の給与には社保が入らない。
--
-- 保険料が発生する月（実務）:
--   資格取得日の属する月 〜 資格喪失日の属する月の「前月」まで。
--   ＝ 月末時点で被保険者資格があれば、その月の保険料が発生する。
--   喪失日は「退職日の翌日」なので、10/31退職なら喪失日は11/1、
--   保険料は10月分まで発生する。
-- =====================================================================

alter table profiles
  add column if not exists shaho_enrolled_on date,
  add column if not exists shaho_left_on     date;

comment on column profiles.shaho_enrolled_on is
  '社会保険の資格取得日。年金機構の「資格取得確認および標準報酬決定通知書」の日付。'
  'この月から給与に社保が入る。NULL なら shaho_enrolled（旧フラグ）で判定する。';
comment on column profiles.shaho_left_on is
  '社会保険の資格喪失日（退職日の翌日）。この日の属する月の前月まで保険料が発生する。'
  'NULL なら加入継続中。';
